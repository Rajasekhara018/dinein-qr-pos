/**
 * Groups the privileges of privilege.json into the applications and features of the Applications hub, following
 * src/app/home/app-feature-rules.json. Pure: used by gen-app-features.mjs and by the spec that proves nothing is left out.
 */

/** The privilegeCode prefix: RIDE_001 -> RIDE, SHARED_0068 -> SHARED. */
export function codePrefix(privilegeCode) {
  return String(privilegeCode).replace(/_?\d+$/, '');
}

function sourceMatches(source, privilege) {
  if (source.codePrefix !== codePrefix(privilege.privilegeCode)) return false;
  if (source.service && source.service !== privilege.service) return false;
  if (source.nameStarts && !source.nameStarts.some((start) => privilege.name.startsWith(start))) return false;
  return true;
}

/**
 * @returns {{ apps: Record<string, {key: string, privileges: string[]}[]>, errors: string[] }}
 * `errors` lists privileges no application takes, privileges no feature takes, ties between features, and empty features.
 */
export function buildAppFeatures(rules, privileges) {
  const errors = [];
  const apps = {};
  for (const app of rules.apps) {
    apps[app.key] = app.features.map((feature) => ({ key: feature.key, privileges: [] }));
  }
  for (const privilege of privileges) {
    const app = rules.apps.find((candidate) => candidate.sources.some((source) => sourceMatches(source, privilege)));
    if (!app) {
      errors.push(`no application takes ${privilege.name} (${privilege.privilegeCode}, service ${privilege.service})`);
      continue;
    }
    let best = [];
    let bestLength = -1;
    app.features.forEach((feature, index) => {
      for (const prefix of feature.prefixes) {
        if (!privilege.name.startsWith(prefix)) continue;
        if (prefix.length > bestLength) {
          best = [index];
          bestLength = prefix.length;
        } else if (prefix.length === bestLength && !best.includes(index)) {
          best.push(index);
        }
      }
    });
    if (best.length === 0) {
      errors.push(`no feature of "${app.key}" takes ${privilege.name}`);
    } else if (best.length > 1) {
      errors.push(`${privilege.name} matches several features of "${app.key}" with the same prefix length`);
    } else {
      apps[app.key][best[0]].privileges.push(privilege.name);
    }
  }
  for (const app of rules.apps) {
    for (const feature of apps[app.key]) {
      if (feature.privileges.length === 0) errors.push(`feature "${app.key}.${feature.key}" has no privilege`);
    }
  }
  return { apps, errors };
}

/** The TypeScript source of home/app-features.generated.ts. */
export function renderGenerated(apps) {
  const lines = [
    '// GENERATED by scripts/gen-app-features.mjs from privilege.json and app-feature-rules.json. Do not edit; run `npm run gen:app-features`.',
    '',
    "import type { AppFeature } from './home.models';",
    '',
    'export const APP_FEATURES: Readonly<Record<string, ReadonlyArray<AppFeature>>> = {',
  ];
  for (const [appKey, features] of Object.entries(apps)) {
    lines.push(`  ${appKey}: [`);
    for (const feature of features) {
      lines.push(`    {`, `      key: '${feature.key}',`, `      privileges: [`);
      for (const name of feature.privileges) lines.push(`        '${name}',`);
      lines.push(`      ],`, `    },`);
    }
    lines.push('  ],');
  }
  lines.push('};', '');
  return lines.join('\n');
}
