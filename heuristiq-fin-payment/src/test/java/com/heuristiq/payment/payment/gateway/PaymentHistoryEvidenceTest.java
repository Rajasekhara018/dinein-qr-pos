package com.heuristiq.payment.payment.gateway;

import com.heuristiq.payment.payment.lifecycle.PaymentLifecycleService;
import com.heuristiq.payment.payment.model.Payment;
import com.heuristiq.payment.payment.model.PaymentStatus;
import com.heuristiq.payment.payment.dto.admin.AdminPayment;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import java.time.LocalDateTime;
import static org.junit.jupiter.api.Assertions.*;

class PaymentHistoryEvidenceTest {
    private JdbcTemplate jdbc;
    private PaymentLifecycleService history;
    private Payment payment;
    @BeforeEach void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:history-"+java.util.UUID.randomUUID()+";DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("CREATE TABLE payment_status_transitions (id BIGINT GENERATED BY DEFAULT AS IDENTITY, payment_id VARCHAR, from_status VARCHAR, to_status VARCHAR, source VARCHAR, reason VARCHAR, transitioned_at TIMESTAMP)");
        history = new PaymentLifecycleService(jdbc);
        payment = new Payment(); payment.setInternalPaymentId("payment-1");
        payment.setCreatedAt(LocalDateTime.of(2026,1,1,0,0));
        payment.setUpdatedAt(LocalDateTime.of(2026,1,2,0,0));
    }
    @Test void legacyHistoryLabelsDerivedStatusRatherThanInventingRecordedCapture() {
        payment.setStatus(PaymentStatus.INITIATED);
        assertEquals(1,history.history(payment).size());
        payment.setStatus(null); assertEquals(1,history.history(payment).size());
        payment.setStatus(PaymentStatus.SETTLED);
        var fallback = history.history(payment);
        assertEquals("DERIVED",fallback.get(1).source());
        assertEquals(AdminPayment.toInstant(payment.getUpdatedAt()),fallback.get(1).transitionedAt());
        payment.setSettledAt(LocalDateTime.of(2026,1,3,0,0));
        assertEquals(AdminPayment.toInstant(payment.getSettledAt()),history.history(payment).get(1).transitionedAt());
        payment.setStatus(PaymentStatus.FAILED);
        assertEquals(AdminPayment.toInstant(payment.getUpdatedAt()),history.history(payment).get(1).transitionedAt());
    }
    @Test void realRecordedTransitionsKeepTheirSourceAndOrderAndDoNotLeakAnotherPayment() {
        jdbc.update("INSERT INTO payment_status_transitions(payment_id,to_status,source,transitioned_at) VALUES (?,?,?,?)", "other","SETTLED","WEBHOOK",null);
        jdbc.update("INSERT INTO payment_status_transitions(payment_id,to_status,source,transitioned_at) VALUES (?,?,?,?)", "payment-1","INITIATED","CHECKOUT",null);
        jdbc.update("INSERT INTO payment_status_transitions(payment_id,from_status,to_status,source,transitioned_at) VALUES (?,?,?,?,?)", "payment-1","INITIATED","SETTLED","VERIFIED_POLL",java.sql.Timestamp.valueOf(payment.getUpdatedAt()));
        payment.setStatus(PaymentStatus.SETTLED);
        var result=history.history(payment);
        assertEquals(2,result.size()); assertEquals("CHECKOUT",result.get(0).source());
        assertNull(result.get(0).transitionedAt()); assertEquals("VERIFIED_POLL",result.get(1).source());
        assertEquals(AdminPayment.toInstant(payment.getUpdatedAt()),result.get(1).transitionedAt());
        jdbc.update("DELETE FROM payment_status_transitions WHERE payment_id=? AND to_status=?","payment-1","INITIATED");
        var partial=history.history(payment);
        assertEquals(2,partial.size()); assertEquals("DERIVED",partial.get(0).source());
        assertEquals("VERIFIED_POLL",partial.get(1).source());
    }
}
