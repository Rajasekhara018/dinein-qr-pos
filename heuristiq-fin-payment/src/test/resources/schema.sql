-- Test-only: payment_status_transitions is written by PaymentLifecycleListener through JDBC, so Hibernate's
-- entity-generated schema does not create it. Mirrors V6__payment_status_transitions.sql for H2.
CREATE TABLE IF NOT EXISTS payment_status_transitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id VARCHAR(255) NOT NULL,
    from_status VARCHAR(32),
    to_status VARCHAR(32) NOT NULL,
    source VARCHAR(64),
    reason VARCHAR(500),
    transitioned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
