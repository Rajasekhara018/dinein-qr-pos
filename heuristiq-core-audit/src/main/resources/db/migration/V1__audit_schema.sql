-- Central audit trail. One table for every event type (ACCESS, SCREEN_VIEW, COMMUNICATION, PAYMENT_GATEWAY,
-- DOMAIN). event_id is the producer's idempotency key; expire_at is set at ingest from the event's retention
-- class and read by the purge job. roles and privilege_ids are comma-delimited with a leading and trailing comma
-- (e.g. ',ADMIN,SUPPORT,') so "has role X" is LIKE '%,X,%'. details holds non-secret string attributes only.
CREATE TABLE audit_events (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       varchar(64)  NOT NULL,
    event_type     varchar(32)  NOT NULL,
    occurred_at    timestamptz  NOT NULL,
    received_at    timestamptz  NOT NULL,
    expire_at      timestamptz  NOT NULL,
    source_service varchar(64),
    user_id        varchar(64),
    user_type      varchar(32),
    role           varchar(64),
    roles          varchar(512),
    privilege_ids  varchar(256),
    feature        varchar(100),
    module         varchar(64),
    screen_key     varchar(100),
    method         varchar(10),
    path           varchar(500),
    status_code    integer,
    outcome        varchar(16),
    duration_ms    bigint,
    correlation_id varchar(100),
    request_id     varchar(100),
    ip_address     varchar(64),
    user_agent     varchar(300),
    app_channel    varchar(32),
    tenant_id      varchar(64),
    details        jsonb,
    CONSTRAINT uk_audit_events_event_id UNIQUE (event_id)
);

CREATE INDEX idx_audit_occurred_at   ON audit_events (occurred_at DESC, id DESC);
CREATE INDEX idx_audit_user_time     ON audit_events (user_id, occurred_at DESC);
CREATE INDEX idx_audit_type_time     ON audit_events (event_type, occurred_at DESC);
CREATE INDEX idx_audit_feature_time  ON audit_events (feature, occurred_at DESC);
CREATE INDEX idx_audit_screen_time   ON audit_events (screen_key, occurred_at DESC);
CREATE INDEX idx_audit_role          ON audit_events (role);
CREATE INDEX idx_audit_outcome       ON audit_events (outcome);
CREATE INDEX idx_audit_correlation   ON audit_events (correlation_id);
CREATE INDEX idx_audit_expire_at     ON audit_events (expire_at);
